import nodeCrypto from "node:crypto";
import type { ContextBase } from "../context.js";
import { ZaloApiError } from "../Errors/ZaloApiError.js";
import { logger, request } from "../utils.js";

/**
 * Zalo encrypts the "sync from another device" payloads with its own protocol library (libzproto),
 * which the web client ships as a wasm-bindgen WebAssembly module.
 *
 * This file locates that module on chat.zalo.me, downloads it and exposes the few functions the
 * sync flow needs. Nothing from Zalo is bundled with zca-js.
 */

const ZALO_WEB_URL = "https://chat.zalo.me/";

export type ZProtoKeyPair = {
    publicKey: Uint8Array;
    privateKey: Uint8Array;
};

export type ZProtoMetadataDecrypted = {
    sessionId: Uint8Array;
    plaintext: Uint8Array;
    senderIdentity: Uint8Array;
    sessionRecord: Uint8Array;
};

export type ZProtoMessageDecrypted = {
    sessionId: Uint8Array;
    plaintext: Uint8Array;
};

export type ZProto = {
    generateKeyPair(): ZProtoKeyPair;
    decryptMetadata(
        ciphertext: Uint8Array,
        identityKey: ZProtoKeyPair,
        ephemeralPrivateKey: Uint8Array,
    ): ZProtoMetadataDecrypted;
    decryptMessage(ciphertext: Uint8Array, sessionRecord: Uint8Array): ZProtoMessageDecrypted;
};

type AnyFunction = (...args: unknown[]) => unknown;
type WasmExports = Record<string, (...args: number[]) => number> & { memory: WebAssembly.Memory };

const REQUIRED_EXPORTS = [
    "memory",
    "__wbindgen_add_to_stack_pointer",
    "__wbindgen_export_0", // store a thrown JS exception
    "__wbindgen_export_1", // free
    "__wbindgen_export_2", // malloc
    "__wbindgen_export_3", // realloc
    "zprotoEd25519GenerateKeyPair",
    "zprotoed25519keypair_publicKey",
    "zprotoed25519keypair_privateKey",
    "__wbg_zprotoed25519keypair_free",
    "zprotoSync2DecryptMetadata",
    "zprotosyncmetadatadecrypted_sessionId",
    "zprotosyncmetadatadecrypted_plaintext",
    "zprotosyncmetadatadecrypted_senderIdentity",
    "zprotosyncmetadatadecrypted_sessionRecord",
    "__wbg_zprotosyncmetadatadecrypted_free",
    "zprotoSync2DecryptMessage",
    "zprotosyncmessagedecrypted_sessionId",
    "zprotosyncmessagedecrypted_plaintext",
    "__wbg_zprotosyncmessagedecrypted_free",
];

const unsupported = (detail: string) =>
    new ZaloApiError(
        `Zalo's sync crypto module (libzproto) is not compatible with this version of zca-js: ${detail}. ` +
            "Zalo probably shipped a new web build, please update zca-js or report this issue.",
    );

/**
 * Instantiate the wasm-bindgen module. This is a port of the glue code generated by wasm-bindgen
 * (found in Zalo's sync-v2-worker bundle), reduced to what the sync flow uses.
 */
function instantiate(bytes: Uint8Array): ZProto {
    // assigned once the module is instantiated, the imports below close over it
    // eslint-disable-next-line prefer-const
    let wasm: WasmExports;
    let lastPanic = "";

    // ---- JS object table shared with the wasm module ----
    const heap: unknown[] = new Array(128).fill(undefined);
    heap.push(undefined, null, true, false);
    let heapNext = heap.length;

    const getObject = (idx: number) => heap[idx];
    const addHeapObject = (obj: unknown) => {
        if (heapNext === heap.length) heap.push(heap.length + 1);
        const idx = heapNext;
        heapNext = heap[idx] as number;
        heap[idx] = obj;
        return idx;
    };
    const takeObject = (idx: number) => {
        const obj = getObject(idx);
        if (idx >= 132) {
            heap[idx] = heapNext;
            heapNext = idx;
        }
        return obj;
    };

    // ---- memory helpers ----
    const textDecoder = new TextDecoder("utf-8", { ignoreBOM: true, fatal: true });
    const textEncoder = new TextEncoder();
    const memU8 = () => new Uint8Array(wasm.memory.buffer);
    const memView = () => new DataView(wasm.memory.buffer);
    const getString = (ptr: number, len: number) => textDecoder.decode(memU8().subarray(ptr >>> 0, (ptr >>> 0) + len));

    let lastLength = 0;
    const passBytes = (data: Uint8Array) => {
        const ptr = wasm.__wbindgen_export_2(data.length, 1) >>> 0;
        memU8().set(data, ptr);
        lastLength = data.length;
        return ptr;
    };
    const passString = (value: string) => passBytes(textEncoder.encode(value));

    const handleError = <T>(fn: () => T): T | undefined => {
        try {
            return fn();
        } catch (error) {
            wasm.__wbindgen_export_0(addHeapObject(error));
            return undefined;
        }
    };

    // ---- imports ----
    // wasm-bindgen suffixes every import with a hash of its signature, e.g. `__wbg_buffer_609cc3eee51ed158`.
    type ImportFn = (...args: number[]) => unknown;
    const exact: Record<string, ImportFn> = {
        __wbg_new_405e22f390576ce2: () => addHeapObject(new Object()),
        __wbg_new_78feb108b6472713: () => addHeapObject([]),
        __wbg_new_8a6f238a6ece86ea: () => addHeapObject(new Error()),
        __wbg_new_a12002a7f91c75be: (a) => addHeapObject(new Uint8Array(getObject(a) as ArrayBuffer)),
        __wbg_call_672a4d21634d4a24: (a, b) =>
            handleError(() => addHeapObject(Reflect.apply(getObject(a) as AnyFunction, getObject(b), []))),
        __wbg_call_7cccdd69e0791ae2: (a, b, c) =>
            handleError(() => addHeapObject(Reflect.apply(getObject(a) as AnyFunction, getObject(b), [getObject(c)]))),
        __wbg_set_3f1d0b984ed272ed: (a, b, c) => {
            (getObject(a) as Record<string, unknown>)[takeObject(b) as string] = takeObject(c);
        },
        __wbg_set_65595bdd868b3009: (a, b, c) => {
            (getObject(a) as Uint8Array).set(getObject(b) as Uint8Array, c >>> 0);
        },
    };
    // imports whose name (without the hash) is unambiguous
    const byName: Record<string, ImportFn> = {
        __wbg_apply: (a, b, c) =>
            handleError(() =>
                addHeapObject(Reflect.apply(getObject(a) as AnyFunction, getObject(b), getObject(c) as unknown[])),
            ),
        __wbg_buffer: (a) => addHeapObject((getObject(a) as { buffer: unknown }).buffer),
        __wbg_crypto: (a) => addHeapObject((getObject(a) as { crypto: unknown }).crypto),
        __wbg_msCrypto: (a) => addHeapObject((getObject(a) as { msCrypto: unknown }).msCrypto),
        __wbg_error: (ptr, len) => {
            try {
                // console_error_panic_hook: keep the message, it is attached to the next thrown error
                lastPanic = getString(ptr, len);
            } finally {
                wasm.__wbindgen_export_1(ptr, len, 1);
            }
        },
        __wbg_getRandomValues: (a, b) =>
            handleError(() => {
                (getObject(a) as Crypto).getRandomValues(getObject(b) as Uint8Array);
            }),
        __wbg_randomFillSync: (a, b) =>
            handleError(() => {
                (getObject(a) as typeof nodeCrypto).randomFillSync(takeObject(b) as Uint8Array);
            }),
        __wbg_newnoargs: (ptr, len) => addHeapObject(new Function(getString(ptr, len))),
        __wbg_newwithbyteoffsetandlength: (a, b, c) =>
            addHeapObject(new Uint8Array(getObject(a) as ArrayBuffer, b >>> 0, c >>> 0)),
        __wbg_newwithlength: (a) => addHeapObject(new Uint8Array(a >>> 0)),
        __wbg_node: (a) => addHeapObject((getObject(a) as { node: unknown }).node),
        __wbg_process: (a) => addHeapObject((getObject(a) as { process: unknown }).process),
        __wbg_versions: (a) => addHeapObject((getObject(a) as { versions: unknown }).versions),
        __wbg_push: (a, b) => (getObject(a) as unknown[]).push(getObject(b)),
        // the module only ever requires "crypto" (to get randomFillSync)
        __wbg_require: () => handleError(() => addHeapObject(() => nodeCrypto)),
        __wbg_stack: (ret, a) => {
            const ptr = passString(String((getObject(a) as Error).stack));
            memView().setInt32(ret + 4, lastLength, true);
            memView().setInt32(ret + 0, ptr, true);
        },
        __wbg_static_accessor_GLOBAL: () => (typeof global === "undefined" ? 0 : addHeapObject(global)),
        __wbg_static_accessor_GLOBAL_THIS: () => addHeapObject(globalThis),
        __wbg_static_accessor_SELF: () => 0,
        __wbg_static_accessor_WINDOW: () => 0,
        __wbg_subarray: (a, b, c) => addHeapObject((getObject(a) as Uint8Array).subarray(b >>> 0, c >>> 0)),
        __wbindgen_is_function: (a) => typeof getObject(a) === "function",
        __wbindgen_is_object: (a) => typeof getObject(a) === "object" && getObject(a) !== null,
        __wbindgen_is_string: (a) => typeof getObject(a) === "string",
        __wbindgen_is_undefined: (a) => getObject(a) === undefined,
        __wbindgen_memory: () => addHeapObject(wasm.memory),
        __wbindgen_number_new: (a) => addHeapObject(a),
        __wbindgen_object_clone_ref: (a) => addHeapObject(getObject(a)),
        __wbindgen_object_drop_ref: (a) => {
            takeObject(a);
        },
        __wbindgen_string_new: (ptr, len) => addHeapObject(getString(ptr, len)),
        __wbindgen_throw: (ptr, len) => {
            throw new Error(getString(ptr, len));
        },
    };

    const module = new WebAssembly.Module(bytes as BufferSource);
    const imports: Record<string, Record<string, ImportFn>> = {};
    for (const entry of WebAssembly.Module.imports(module)) {
        if (entry.kind !== "function") throw unsupported(`unexpected import ${entry.module}.${entry.name}`);
        const impl = exact[entry.name] ?? byName[entry.name] ?? byName[entry.name.replace(/_[0-9a-f]{16}$/, "")];
        if (!impl) throw unsupported(`unknown import ${entry.module}.${entry.name}`);
        (imports[entry.module] ??= {})[entry.name] = impl;
    }

    wasm = new WebAssembly.Instance(module, imports).exports as WasmExports;
    for (const name of REQUIRED_EXPORTS) {
        if (!(name in wasm)) throw unsupported(`missing export ${name}`);
    }

    /** Call an export that returns `Result<pointer, JsValue>` through the stack return area */
    const callForPointer = (fn: (retPtr: number) => void) => {
        const retPtr = wasm.__wbindgen_add_to_stack_pointer(-16);
        try {
            try {
                fn(retPtr);
            } catch (error) {
                // a trap inside the module (WebAssembly.RuntimeError), usually preceded by a panic message
                const detail = lastPanic || (error instanceof Error ? error.message : String(error));
                lastPanic = "";
                throw new ZaloApiError(`libzproto crashed: ${detail}`);
            }
            const view = memView();
            const value = view.getInt32(retPtr + 0, true);
            const error = view.getInt32(retPtr + 4, true);
            const isError = view.getInt32(retPtr + 8, true);
            if (isError) {
                const thrown = takeObject(error);
                let detail: string;
                if (thrown instanceof Error) detail = thrown.message;
                else if (typeof thrown === "object" && thrown !== null) detail = JSON.stringify(thrown);
                else detail = String(thrown);
                throw new ZaloApiError(`libzproto error: ${detail}`);
            }
            return value >>> 0;
        } finally {
            wasm.__wbindgen_add_to_stack_pointer(16);
        }
    };
    const readBytes = (getter: string, ptr: number) => (takeObject(wasm[getter](ptr)) as Uint8Array).slice();

    return {
        generateKeyPair() {
            const ptr = callForPointer((ret) => wasm.zprotoEd25519GenerateKeyPair(ret));
            try {
                return {
                    publicKey: readBytes("zprotoed25519keypair_publicKey", ptr),
                    privateKey: readBytes("zprotoed25519keypair_privateKey", ptr),
                };
            } finally {
                wasm.__wbg_zprotoed25519keypair_free(ptr, 0);
            }
        },
        decryptMetadata(ciphertext, identityKey, ephemeralPrivateKey) {
            const ptr = callForPointer((ret) => {
                const p0 = passBytes(ciphertext);
                const l0 = lastLength;
                const p1 = passBytes(identityKey.publicKey);
                const l1 = lastLength;
                const p2 = passBytes(identityKey.privateKey);
                const l2 = lastLength;
                const p3 = passBytes(ephemeralPrivateKey);
                const l3 = lastLength;
                // last (ptr, len) pair is an optional string that the web client never passes
                wasm.zprotoSync2DecryptMetadata(ret, p0, l0, p1, l1, p2, l2, p3, l3, 0, 0);
            });
            try {
                return {
                    sessionId: readBytes("zprotosyncmetadatadecrypted_sessionId", ptr),
                    plaintext: readBytes("zprotosyncmetadatadecrypted_plaintext", ptr),
                    senderIdentity: readBytes("zprotosyncmetadatadecrypted_senderIdentity", ptr),
                    sessionRecord: readBytes("zprotosyncmetadatadecrypted_sessionRecord", ptr),
                };
            } finally {
                wasm.__wbg_zprotosyncmetadatadecrypted_free(ptr, 0);
            }
        },
        decryptMessage(ciphertext, sessionRecord) {
            const ptr = callForPointer((ret) => {
                const p0 = passBytes(ciphertext);
                const l0 = lastLength;
                const p1 = passBytes(sessionRecord);
                const l1 = lastLength;
                wasm.zprotoSync2DecryptMessage(ret, p0, l0, p1, l1);
            });
            try {
                return {
                    sessionId: readBytes("zprotosyncmessagedecrypted_sessionId", ptr),
                    plaintext: readBytes("zprotosyncmessagedecrypted_plaintext", ptr),
                };
            } finally {
                wasm.__wbg_zprotosyncmessagedecrypted_free(ptr, 0);
            }
        },
    };
}

const SCRIPT_HEADERS = {
    accept: "*/*",
    "sec-fetch-dest": "script",
    "sec-fetch-mode": "no-cors",
    "sec-fetch-site": "same-origin",
};

async function fetchOk(ctx: ContextBase, url: string, headers: Record<string, string>) {
    const response = await request(ctx, url, { method: "GET", headers });
    if (!response.ok) throw new ZaloApiError(`Failed to load ${url}: ${response.status} ${response.statusText}`);
    return response;
}

/**
 * chat.zalo.me (html) -> sync-v2-worker.<hash>.js -> libs/libzproto_wasm_bg.<hash>.wasm
 */
async function findWasmUrl(ctx: ContextBase) {
    const html = await (
        await fetchOk(ctx, ZALO_WEB_URL, { accept: "text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8" })
    ).text();

    const workerName = html.match(/sync-v2-worker\.[0-9a-f]+\.js/)?.[0];
    if (!workerName) throw unsupported("cannot find the sync worker script on chat.zalo.me");

    const worker = await (await fetchOk(ctx, new URL(workerName, ZALO_WEB_URL).href, SCRIPT_HEADERS)).text();
    const wasmPath = worker.match(/libs\/libzproto_wasm_bg\.[0-9a-f]+\.wasm/)?.[0];
    if (!wasmPath) throw unsupported("cannot find the libzproto module in the sync worker script");

    return new URL(wasmPath, ZALO_WEB_URL).href;
}

let cached: ZProto | null = null;
let pending: Promise<ZProto> | null = null;

/**
 * Download (once per process) and instantiate Zalo's libzproto module
 */
export async function loadZProto(ctx: ContextBase): Promise<ZProto> {
    if (cached) return cached;
    if (pending) return pending;

    pending = (async () => {
        const url = await findWasmUrl(ctx);
        const bytes = new Uint8Array(await (await fetchOk(ctx, url, { accept: "*/*" })).arrayBuffer());
        cached = instantiate(bytes);
        logger(ctx).verbose("Loaded libzproto from", url);
        return cached;
    })();

    try {
        return await pending;
    } finally {
        pending = null;
    }
}

